"""Request and response models for server configuration validation."""

from typing import Annotated, Literal
from datetime import datetime, timezone

from pydantic import BaseModel, ConfigDict, Field, StrictBool, field_validator


class CreateServerRequest(BaseModel):
    """The allowed server settings for the local CloudOps MVP."""

    model_config = ConfigDict(extra="forbid")

    name: Annotated[
        str,
        Field(
            min_length=3,
            max_length=32,
            pattern=r"^[a-z][a-z0-9-]*[a-z0-9]$",
        ),
    ]
    environment: Literal["development", "staging"]
    region: Literal["ca-central-1", "us-east-1"]
    instance_type: Literal["t3.micro", "t3.small"]
    install_nginx: StrictBool
    install_docker: StrictBool


# Preserve the Day 2 import name while sharing one set of validation rules.
ServerConfiguration = CreateServerRequest


class ServerRequestResponse(CreateServerRequest):
    """A saved request, including fields generated by the server."""

    model_config = ConfigDict(extra="forbid", from_attributes=True)

    id: str
    status: Literal["queued"]
    created_at: datetime

    @field_validator("created_at")
    @classmethod
    def ensure_utc(cls, value: datetime) -> datetime:
        # SQLite returns naive datetimes; our stored timestamps are always UTC.
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)


class ValidationResponse(BaseModel):
    """A configuration that passed validation."""

    status: Literal["validated"] = "validated"
    configuration: ServerConfiguration


class TerraformPlanSummary(BaseModel):
    """The deliberately small, non-sensitive summary returned from a local plan."""

    resource: Literal["terraform_data.server_configuration"]
    to_add: int = Field(ge=0)
    to_change: int = Field(ge=0)
    to_destroy: int = Field(ge=0)


class ProvisioningJobResponse(BaseModel):
    """A provisioning job and its sanitized, optional plan result."""

    model_config = ConfigDict(extra="forbid", from_attributes=True)

    id: str
    server_request_id: str
    status: Literal["queued", "planning", "plan_ready", "failed"]
    plan_summary: TerraformPlanSummary | None
    error_message: str | None
